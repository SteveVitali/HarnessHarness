#!/usr/bin/env bash
# gen-test-pki.sh — regenerate the committed TEST-ONLY PKI fixtures
# (R4.5c; the ADR-0365 TLS battery).
#
#   scripts/gen-test-pki.sh [out-dir]     # default crates/hh-tls/fixtures/pki
#
# Everything this writes is THROWAWAY test material — a local CA, a server
# cert (SAN IP:127.0.0.1 / DNS:localhost / DNS:hh.test), a SAN-mismatch
# cert signed by the same CA, a client cert for the mTLS legs, and a
# rogue CA + rogue-issued server cert for the untrusted-issuer leg.
# 3650-day expiry (deterministic fixtures, never live material). The
# private keys are test-only by construction and are allowlisted in
# .gitleaks.toml — they exist so hermetic fixtures can terminate TLS;
# they must NEVER be used outside these tests.
set -euo pipefail

OUT="${1:-crates/hh-tls/fixtures/pki}"
mkdir -p "$OUT"
TMPD=$(mktemp -d); trap 'rm -rf "$TMPD"' EXIT
DAYS=3650
ORG="/O=HarnessHarness test fixtures (TEST-ONLY - not a real CA)"

ca() { # $1 name — writes $OUT/$1.pem (cert) + $TMPD/$1-key.pem (key)
  openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days "$DAYS" \
    -subj "/CN=$1$ORG" \
    -keyout "$TMPD/$1-key.pem" -out "$OUT/$1.pem" 2>/dev/null
}

issue() { # $1 cn $2 san $3 ca-name $4 out-name $5 eku — cert+key under $OUT
  openssl req -newkey rsa:2048 -nodes -sha256 \
    -subj "/CN=$1$ORG" \
    -keyout "$OUT/$4-key.pem" -out "$TMPD/$4.csr" 2>/dev/null
  printf 'basicConstraints=CA:FALSE\nsubjectAltName=%s\nextendedKeyUsage=%s\n' \
    "$2" "$5" > "$TMPD/$4.ext"
  openssl x509 -req -in "$TMPD/$4.csr" \
    -CA "$OUT/$3.pem" -CAkey "$TMPD/$3-key.pem" \
    -CAserial "$TMPD/$3.srl" -CAcreateserial \
    -days "$DAYS" -sha256 -extfile "$TMPD/$4.ext" -out "$OUT/$4.pem" 2>/dev/null
}

ca hh-test-ca
issue hh-test-server "DNS:localhost,DNS:hh.test,IP:127.0.0.1" hh-test-ca server serverAuth
issue hh-test-server-wrongname "DNS:other.example" hh-test-ca wrongname serverAuth
issue hh-test-client "DNS:hh-client.test" hh-test-ca client clientAuth
ca rogue-ca
issue rogue-server "DNS:localhost,IP:127.0.0.1" rogue-ca rogue-server serverAuth

cat > "$OUT/README.md" <<'MD'
# TEST-ONLY PKI fixtures (R4.5c / ADR-0365)

Throwaway material regenerated by `scripts/gen-test-pki.sh` — the private
keys exist so hermetic tests can terminate TLS locally. They are marked
test-only, allowlisted in `.gitleaks.toml`, and must never be used
outside the test batteries.

- `ca.pem` — the test root the extra-roots hook consumes.
- `server.pem` / `server-key.pem` — SAN `IP:127.0.0.1, DNS:localhost, DNS:hh.test`.
- `wrongname.pem` / `wrongname-key.pem` — CA-signed, SAN `DNS:other.example` (the wrong-SAN leg).
- `client.pem` / `client-key.pem` — `CN=hh-test-client`, SAN `DNS:hh-client.test` (mTLS legs).
- `rogue-ca.pem`, `rogue-server*.pem` — an unrelated issuer (the untrusted-chain leg).
MD
printf 'wrote %s\n' "$OUT"
