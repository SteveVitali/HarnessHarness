//! `dpop` — `SenderConstraint::Dpop` proof-of-possession verification
//! (R3.7; DF-S1.13-1's last residual; ADR-0342 D2's revisit trigger fired
//! by the operator's HUMAN-H5 ruling; ADR-0359 admits `ring =0.17.14` for
//! exactly this surface).
//!
//! # The one construction (CC1)
//!
//! Every `dpop` check on every delivery mode verifies **here** — `bind`
//! verifies a bind-context proof and records the bound key on the binding
//! (`CredentialBinding.sender_key`); `mediate`/`mediate_sentinel`, `mint`,
//! `verify_minted` and `deliver_wrapped` each require a verb-context proof
//! *by the bound key* over the verb's canonical preimage. There is no
//! second proof-check spelling anywhere in the workspace.
//!
//! # The proof envelope
//!
//! `DpopProof{alg, public_key, signature}` is the closed record a caller
//! presents — the raw public-key bytes and the raw signature over a
//! verb-framed preimage (`hh.dpop.v1 ␟ <context> ␟ <field>…` — U+001F
//! separators, one domain tag per verb so a proof minted for one verb
//! replays nowhere else). Failure modes — an absent proof, a key that
//! differs from the bound `sender_key`, a malformed key, a signature that
//! does not verify — are all `Refused{sender_constraint_unmet}` (CC3:
//! refused, never skipped, never a fabricated accept).
//!
//! # Honesty bounds
//!
//! Verification is **fixture-verified**: the signatures are real —
//! generated by `ring` at test time (`fixture` below) and verified by
//! `ring` on the live path — but the keys are fixture constructions, not
//! custody evidence (OQ-170) and no issuer/JWK/JWT exchange runs. The
//! kernel-resident `kernel_use` path is *not* a sender-constrained
//! delivery (no destination, and the kernel holds no holder key to
//! produce a signature) — the constraint binds deliveries to
//! destinations, never the kernel's own read.

use hh_wire::sha256::sha256_hex;

/// The closed proof-algorithm sum — the two `ring` verification
/// algorithms ADR-0359 D2 admits (`ED25519` and
/// `ECDSA_P256_SHA256_ASN1`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DpopAlg {
    /// Ed25519 — a raw 32-byte public key and a 64-byte signature.
    Ed25519,
    /// ECDSA P-256/SHA-256 — an uncompressed SEC-1 public key (65 bytes)
    /// and an ASN.1-DER signature.
    Es256,
}

impl DpopAlg {
    /// The canonical tag.
    pub fn as_str(self) -> &'static str {
        match self {
            DpopAlg::Ed25519 => "ed25519",
            DpopAlg::Es256 => "es256",
        }
    }

    /// Parse the closed sum.
    pub fn parse(s: &str) -> Option<DpopAlg> {
        match s {
            "ed25519" => Some(DpopAlg::Ed25519),
            "es256" => Some(DpopAlg::Es256),
            _ => None,
        }
    }
}

/// `DpopProof{alg, public_key, signature}` — the proof-of-possession
/// material a `bind`/request descriptor carries. Raw bytes only: the
/// envelope is the fixture form of a signed PoP (a JWT/JWK spelling is
/// the live-issuer leg's, out of scope).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DpopProof {
    /// The algorithm the signature was made under.
    pub alg: DpopAlg,
    /// The raw public-key bytes (32 for `ed25519`, 65 uncompressed-SEC-1
    /// for `es256`).
    pub public_key: Vec<u8>,
    /// The raw signature bytes over the verb's canonical preimage.
    pub signature: Vec<u8>,
}

impl DpopProof {
    /// The bound-key coordinate — `dpop:<alg>:<sha256-hex(public_key)[..32]>`.
    /// Deterministic and content-free: `bind` records it on the binding and
    /// the `bound`/`wrapped` audit rows; a request's proof must produce the
    /// identical coordinate (proof-of-**possession of the bound key**).
    pub fn sender_key(&self) -> String {
        let digest = sha256_hex(&self.public_key);
        format!("dpop:{}:{}", self.alg.as_str(), &digest[..32])
    }

    /// The one verification construction (ADR-0359 D2 — `ring`'s
    /// `UnparsedPublicKey` verify; `false` for a malformed key or a
    /// signature that does not verify — the caller maps it to
    /// `sender_constraint_unmet`).
    pub fn verify(&self, preimage: &str) -> bool {
        let alg: &'static dyn ring::signature::VerificationAlgorithm = match self.alg {
            DpopAlg::Ed25519 => &ring::signature::ED25519,
            DpopAlg::Es256 => &ring::signature::ECDSA_P256_SHA256_ASN1,
        };
        ring::signature::UnparsedPublicKey::new(alg, &self.public_key)
            .verify(preimage.as_bytes(), &self.signature)
            .is_ok()
    }
}

/// The canonical preimage frame — `hh.dpop.v1 ␟ <context> ␟ <field>…`
/// (U+001F separators can never appear inside a member spelling; one
/// context tag per verb so proofs never replay across verbs).
fn frame(context: &str, fields: &[&str]) -> String {
    let mut s = format!("hh.dpop.v1\u{1f}{context}");
    for f in fields {
        s.push('\u{1f}');
        s.push_str(f);
    }
    s
}

/// `bind`'s proof context — the bound key is established over
/// `(channel, holder, env, mode, decision_ref)`: the proof attests the
/// *holder* controls the key this binding will pin.
pub fn bind_preimage(
    channel_id: &str,
    holder: &str,
    env_handle: &str,
    mode: &str,
    monitor_decision_ref: &str,
) -> String {
    frame(
        "bind",
        &[channel_id, holder, env_handle, mode, monitor_decision_ref],
    )
}

/// A request-time proof — `mediate`/`mediate_sentinel`/`deliver_wrapped`
/// all sign the same request shape (the `method`/`path` members are
/// `""`/`"-"` when the delivery carries none — the frame is total, never
/// elided).
pub fn request_preimage(
    binding_id: &str,
    method: Option<&str>,
    destination: &str,
    path: Option<&str>,
    effect_id: &str,
) -> String {
    frame(
        "request",
        &[
            binding_id,
            method.unwrap_or("-"),
            destination,
            path.unwrap_or("-"),
            effect_id,
        ],
    )
}

/// `mint`'s proof context — minting a `minted_scoped` token on a `dpop`
/// channel requires a bound-key signature over `(binding, audience)`; the
/// token then records the bound `sender_key`.
pub fn mint_preimage(binding_id: &str, audience: &str) -> String {
    frame("mint", &[binding_id, audience])
}

/// `verify_minted`'s presentation context — presenting a `dpop`-bound
/// token at the destination requires a bound-key signature over the token
/// spelling itself plus the claimed audience (the `ath`-analogue: the
/// proof is bound to *this* token, never replayable for another).
pub fn presentation_preimage(token: &str, audience: &str) -> String {
    frame("token", &[token, audience])
}

/// The fixture construction — test-time proof generation over `ring`'s
/// signing half. ADR-0359 D2 admits the keygen/sign APIs **for fixtures
/// only**: they produce real signatures over real preimages so the
/// verifier runs honestly end-to-end — they are never a key-custody,
/// issuer or live-attestation claim (OQ-170; the build's verified ceiling
/// is fixture-verified).
pub mod fixture {
    use super::{DpopAlg, DpopProof};
    use ring::signature::KeyPair;

    /// The signing half of a fixture keypair — kept behind a boxed
    /// closure so `FixtureKey` holds one shape across algorithms.
    type SignFn = Box<dyn Fn(&[u8]) -> Vec<u8>>;

    /// A fixture keypair that stays alive — one key, many signatures
    /// (per-verb proofs over `bind`/`request`/`mint`/`presentation`
    /// preimages are all by *the same* bound key, as real PoP requires).
    /// The private half never leaves the fixture: `proof_for` is the only
    /// way material crosses.
    pub struct FixtureKey {
        alg: DpopAlg,
        public_key: Vec<u8>,
        sign: SignFn,
    }

    impl FixtureKey {
        /// The bound-key coordinate (`DpopProof::sender_key` of every
        /// proof this key makes).
        pub fn sender_key(&self) -> String {
            self.proof_for("").sender_key()
        }

        /// Sign `preimage` and package the proof.
        pub fn proof_for(&self, preimage: &str) -> DpopProof {
            DpopProof {
                alg: self.alg,
                public_key: self.public_key.clone(),
                signature: (self.sign)(preimage.as_bytes()),
            }
        }
    }

    /// Generate a fresh fixture key of `alg`. Panics on an entropy/keygen
    /// failure — a fixture that cannot sign must fail loudly, never
    /// produce a passing verdict by construction.
    pub fn generate(alg: DpopAlg) -> FixtureKey {
        let rng = ring::rand::SystemRandom::new();
        match alg {
            DpopAlg::Ed25519 => {
                let pkcs8 = ring::signature::Ed25519KeyPair::generate_pkcs8(&rng)
                    .expect("fixture: ed25519 keygen");
                let kp = ring::signature::Ed25519KeyPair::from_pkcs8(pkcs8.as_ref())
                    .expect("fixture: ed25519 pkcs8 decode");
                FixtureKey {
                    alg,
                    public_key: kp.public_key().as_ref().to_vec(),
                    sign: Box::new(move |m: &[u8]| kp.sign(m).as_ref().to_vec()),
                }
            }
            DpopAlg::Es256 => {
                let pkcs8 = ring::signature::EcdsaKeyPair::generate_pkcs8(
                    &ring::signature::ECDSA_P256_SHA256_ASN1_SIGNING,
                    &rng,
                )
                .expect("fixture: es256 keygen");
                let kp = ring::signature::EcdsaKeyPair::from_pkcs8(
                    &ring::signature::ECDSA_P256_SHA256_ASN1_SIGNING,
                    pkcs8.as_ref(),
                    &ring::rand::SystemRandom::new(),
                )
                .expect("fixture: es256 pkcs8 decode");
                let rng = ring::rand::SystemRandom::new();
                FixtureKey {
                    alg,
                    public_key: kp.public_key().as_ref().to_vec(),
                    sign: Box::new(move |m: &[u8]| {
                        kp.sign(&rng, m)
                            .expect("fixture: es256 sign")
                            .as_ref()
                            .to_vec()
                    }),
                }
            }
        }
    }

    /// Generate a fresh fixture key of `alg` and sign `preimage` (the
    /// one-shot form of `generate(alg).proof_for(preimage)`).
    pub fn signed_proof(alg: DpopAlg, preimage: &str) -> DpopProof {
        generate(alg).proof_for(preimage)
    }
}
